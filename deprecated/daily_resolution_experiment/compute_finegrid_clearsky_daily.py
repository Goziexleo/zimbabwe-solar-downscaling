"""Compute the fine (0.1 deg) grid climatological clear-sky GHI ceiling at
DAILY (not monthly) resolution.

This supports a daily-resolution retraining experiment testing whether the
312-monthly-sample training set is limiting validation R (Table 3.3): solar
geometry for a given day-of-year is effectively identical from year to year,
so one climatological field per day-of-year is computed and reused for every
year in the training/validation periods, exactly as compute_finegrid_clearsky_ghi.py
does per month.

Both Ineichen inputs are cell-specific, matching compute_finegrid_clearsky_ghi.py.
An earlier version of this script passed altitude=1000.0 m and
linke_turbidity=3.0 as domain-wide constants - the same defect that was
corrected in the monthly script - which left this daily variant inconsistent
with the deployed monthly climatology. Station altitude is now the per-cell
SRTM elevation of Section 3.5.2 and Linke turbidity is the per-cell PVLIB
climatology, linearly interpolated between mid-month anchors so that it varies
smoothly across the year and reduces exactly to the monthly script's value on
the 15th of each month.

IMPORTANT: the on-disk clearsky_ghi_finegrid_climatology_daily.nc predates this
correction. It must be regenerated by rerunning this script before any daily
experiment is revisited; the daily CSI datasets derived from it are likewise
stale. As with the monthly case the clear-sky specification cancels exactly
from reconstructed GHI (build_fine_grid_csi divides by this field and
csi_to_ghi multiplies by it again, and the [0, 1.1] clip does not bind), so
this affects the physical defensibility of the CSI intermediate rather than
the final product.
"""

import os
import numpy as np
import xarray as xr
import pandas as pd
import h5py
import pvlib

from ml_dataset_common import FINE_LAT, FINE_LON

TOPO_PATH = os.path.abspath("./data/processed/topography/zimbabwe_topographic_features_0.1deg.nc")


def linke_turbidity_grid(lat_1d, lon_1d):
    """Per-cell, per-month Linke turbidity from the climatology shipped with
    PVLIB. pvlib.clearsky.lookup_linke_turbidity only accepts scalar
    coordinates, so the documented index convention is reproduced here in
    vectorised form and checked against the library function below. Identical
    to the function in compute_finegrid_clearsky_ghi.py."""
    lon_2d, lat_2d = np.meshgrid(lon_1d, lat_1d)

    # latitude: 2160 rows spanning +90 to -90; longitude: 4320 columns spanning -180 to +180
    lat_idx = np.clip(np.around((lat_2d - (90.0 - 1 / 24.0)) * -12.0).astype(int), 0, 2159)
    lon_idx = np.clip(np.around((lon_2d - (-180.0 + 1 / 24.0)) * 12.0).astype(int), 0, 4319)

    # h5py cannot take paired fancy indices, so read the bounding box that
    # covers the domain (a few thousand cells) and index it with numpy.
    lat0, lat1 = int(lat_idx.min()), int(lat_idx.max())
    lon0, lon1 = int(lon_idx.min()), int(lon_idx.max())
    h5_path = os.path.join(os.path.dirname(pvlib.__file__), "data", "LinkeTurbidities.h5")
    with h5py.File(h5_path, "r") as f:
        block = f["LinkeTurbidity"][lat0:lat1 + 1, lon0:lon1 + 1, :]

    return block[lat_idx - lat0, lon_idx - lon0, :] / 20.0


def interpolate_turbidity_to_doy(turbidity_monthly, reference_year, n_days):
    """Expand a (n_lat, n_lon, 12) mid-month turbidity climatology to
    (n_days, n_lat, n_lon) by linear interpolation in day-of-year.

    The PVLIB climatology is a monthly field whose values are taken to apply at
    the middle of each month, so the anchors are the day-of-year of the 15th.
    The series is wrapped periodically (December's anchor is repeated before
    January's and vice versa) so 1 January and 31 December are interpolated
    rather than clamped. On the 15th of any month the result equals the monthly
    value exactly, which is the date compute_finegrid_clearsky_ghi.py evaluates.
    """
    anchors = np.array([
        pd.Timestamp(year=reference_year, month=m, day=15).dayofyear
        for m in range(1, 13)
    ], dtype=float)

    # Periodic wrap: previous December and next January.
    anchors_wrapped = np.concatenate(([anchors[-1] - n_days], anchors, [anchors[0] + n_days]))
    values_wrapped = np.concatenate(
        (turbidity_monthly[:, :, -1:], turbidity_monthly, turbidity_monthly[:, :, :1]), axis=2
    )

    doys = np.arange(1, n_days + 1, dtype=float)
    n_lat, n_lon = turbidity_monthly.shape[:2]
    out = np.empty((n_days, n_lat, n_lon))
    for i in range(n_lat):
        for j in range(n_lon):
            out[:, i, j] = np.interp(doys, anchors_wrapped, values_wrapped[i, j, :])
    return out


# --- Configuration ---
output_dir = os.path.abspath("./data/processed/era5/csi_finegrid")
os.makedirs(output_dir, exist_ok=True)
output_path = os.path.join(output_dir, "clearsky_ghi_finegrid_climatology_daily.nc")

REFERENCE_YEAR = 2001  # non-leap year; only day-of-year matters for solar geometry

print("Using canonical core-domain fine (0.1 deg) target grid (Section 3.2.1, no buffer)...")
fine_lat = FINE_LAT
fine_lon = FINE_LON
n_lat, n_lon = len(fine_lat), len(fine_lon)
print(f"Fine grid: {n_lat} lat x {n_lon} lon = {n_lat * n_lon} cells")

lon_2d, lat_2d = np.meshgrid(fine_lon, fine_lat)
lat_flat = lat_2d.flatten()
lon_flat = lon_2d.flatten()

# --- Cell-specific station altitude (Section 3.5.2 SRTM elevation) ---
print("Loading SRTM-derived elevation for cell-specific altitude...")
ds_topo = xr.open_dataset(TOPO_PATH)
topo_lat_name = "lat" if "lat" in ds_topo.coords else "y"
topo_lon_name = "lon" if "lon" in ds_topo.coords else "x"
ds_topo = ds_topo.rename({topo_lat_name: "lat", topo_lon_name: "lon"}).sortby("lat")
elevation = ds_topo["elevation"].interp(lat=fine_lat, lon=fine_lon, method="linear").values
if np.isnan(elevation).any():
    # The fine grid sits strictly inside the DEM footprint, so any NaN here
    # would signal a grid/DEM mismatch rather than an expected edge effect.
    raise RuntimeError(f"Elevation has {np.isnan(elevation).mean():.4%} NaN on the fine grid.")
elev_flat = elevation.flatten()
pressure_flat = pvlib.atmosphere.alt2pres(elev_flat)
print(f"  Elevation {elev_flat.min():.0f} to {elev_flat.max():.0f} m (mean {elev_flat.mean():.0f} m)")

daytime_hours = np.linspace(6.0, 18.0, 13)
n_days = 365
daily_clearsky = np.zeros((n_days, n_lat, n_lon))

# --- Cell-specific, day-of-year-specific Linke turbidity ---
print("Reading per-cell Linke turbidity climatology (PVLIB) and interpolating to day-of-year...")
turbidity_monthly = linke_turbidity_grid(fine_lat, fine_lon)
_probe = pvlib.clearsky.lookup_linke_turbidity(
    pd.DatetimeIndex([f"{REFERENCE_YEAR}-01-15"]), float(fine_lat[0]), float(fine_lon[0]),
    interp_turbidity=False,
).iloc[0]
assert abs(_probe - turbidity_monthly[0, 0, 0]) < 1e-9, (
    f"Vectorised turbidity lookup ({turbidity_monthly[0, 0, 0]:.4f}) disagrees with "
    f"pvlib.lookup_linke_turbidity ({_probe:.4f})."
)
turbidity_daily = interpolate_turbidity_to_doy(turbidity_monthly, REFERENCE_YEAR, n_days)
# The interpolation must be exact on the mid-month anchors the monthly script uses.
for _m in range(1, 13):
    _anchor_doy = pd.Timestamp(year=REFERENCE_YEAR, month=_m, day=15).dayofyear
    assert np.allclose(turbidity_daily[_anchor_doy - 1], turbidity_monthly[:, :, _m - 1]), (
        f"Day-of-year turbidity does not reproduce the monthly value for month {_m}."
    )
print(f"  Turbidity January {turbidity_monthly[:, :, 0].min():.2f}-{turbidity_monthly[:, :, 0].max():.2f}, "
      f"July {turbidity_monthly[:, :, 6].min():.2f}-{turbidity_monthly[:, :, 6].max():.2f}")

base_date = pd.Timestamp(year=REFERENCE_YEAR, month=1, day=1)

for doy_idx in range(n_days):
    day_date = base_date + pd.Timedelta(days=doy_idx)
    if (doy_idx + 1) % 30 == 0 or doy_idx == 0:
        print(f"  Computing day-of-year {doy_idx + 1}/{n_days} ({day_date.date()})...")
    accumulated_cs_ghi = np.zeros(lat_flat.shape)
    turbidity_flat = turbidity_daily[doy_idx].flatten()

    for hour in daytime_hours:
        hour_dt = pd.Timestamp(
            year=day_date.year, month=day_date.month, day=day_date.day,
            hour=int(hour), minute=int((hour % 1) * 60),
        )
        time_repeated = pd.DatetimeIndex([hour_dt] * len(lat_flat))

        solpos = pvlib.solarposition.get_solarposition(time_repeated, lat_flat, lon_flat)
        sza_flat = np.clip(solpos["apparent_zenith"].values, 0.0, 89.9)

        rel_airmass = pvlib.atmosphere.get_relative_airmass(sza_flat)
        abs_airmass = pvlib.atmosphere.get_absolute_airmass(rel_airmass, pressure_flat)

        dni_extra = pvlib.irradiance.get_extra_radiation(hour_dt)
        clearsky = pvlib.clearsky.ineichen(
            sza_flat, abs_airmass, linke_turbidity=turbidity_flat,
            altitude=elev_flat, dni_extra=dni_extra,
        )
        ghi_hr = clearsky["ghi"].values if hasattr(clearsky["ghi"], "values") else clearsky["ghi"]
        accumulated_cs_ghi += np.nan_to_num(ghi_hr, nan=0.0)

    mean_cs_ghi = accumulated_cs_ghi / len(daytime_hours)
    mean_cs_ghi = np.where(mean_cs_ghi < 1.0, 1.0, mean_cs_ghi)
    daily_clearsky[doy_idx] = mean_cs_ghi.reshape(lat_2d.shape)

ds_out = xr.Dataset(
    {"clearsky_ghi": (("doy", "lat", "lon"), daily_clearsky)},
    coords={"doy": np.arange(1, n_days + 1), "lat": fine_lat, "lon": fine_lon},
)
ds_out["clearsky_ghi"].attrs["units"] = "W m-2"
ds_out["clearsky_ghi"].attrs["description"] = (
    "Daytime-averaged (06-18h local) day-of-year-climatological clear-sky GHI "
    "(PVLIB Ineichen model) at the 0.1 deg fine target grid, daily-resolution variant. "
    "Station altitude is the per-cell SRTM elevation and Linke turbidity is the "
    "per-cell PVLIB climatology interpolated from mid-month anchors to day-of-year, "
    "consistent with compute_finegrid_clearsky_ghi.py."
)
ds_out.to_netcdf(output_path)
print(f"\nSuccess! Daily fine-grid clear-sky GHI climatology saved to: {output_path}")
