def is_field(r):
    x = r._r.xml
    return ("fldChar" in x) or ("instrText" in x)


def apply(par, old, new):
    for r in par.runs:
        if old in r.text:
            r.text = r.text.replace(old, new, 1)
            return True
    runs = par.runs
    full = "".join(r.text for r in runs)
    at = full.find(old)
    if at < 0:
        return False
    starts, pos = [], 0
    for r in runs:
        starts.append(pos)
        pos += len(r.text)
    f = max(i for i, st in enumerate(starts) if st <= at)
    l = max(i for i, st in enumerate(starts) if st < at + len(old))
    span = runs[f:l + 1]
    if any(is_field(r) for r in span):
        return False
    acc = "".join(r.text for r in span)
    k = acc.find(old)
    span[0].text = acc[:k] + new + acc[k + len(old):]
    for r in span[1:]:
        r.text = ""
    return True


def main():
    if os.path.exists(LOCK):
        print("The dissertation is open in Word. Close it first.")
        return 2
    d = docx.Document(DOC)
    NS = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}sectPr"
    before = (d.element.xml.count("ZOTERO_ITEM"),
              d.element.xml.count('w:fldCharType="begin"'),
              len(d.element.body.findall(NS)))
    done = left = 0
    for old, new in EDITS:
        # Already applied when the pointer is present; the key text survives the
        # edit, so presence of the key alone does not mean outstanding.
        tail = new[len(old):].strip() if new.startswith(old) else new[-60:]
        if any(tail[:50] in p.text for p in d.paragraphs):
            print("  already applied: %s" % old[:50])
            continue
        par = next((p for p in d.paragraphs if old in p.text), None)
        if par is None:
            left += 1
            print("  NOT FOUND: %s" % old[:50])
            continue
        if apply(par, old, new):
            done += 1
            print("  referenced: %s" % tail[:62])
        else:
            left += 1
            print("  SPANS A FIELD, skipped: %s" % old[:50])

    if not done:
        print("nothing to change")
        return 0 if left == 0 else 1
    bak = DOC.replace(".docx", "_BACKUP_pre_appendixc_refs.docx")
    shutil.copy(DOC, bak)
    d.save(DOC)
    dd = docx.Document(DOC)
    ax = dd.element.xml
    after = (ax.count("ZOTERO_ITEM"), ax.count('w:fldCharType="begin"'),
             len(dd.element.body.findall(NS)))
    if after != before:
        shutil.copy(bak, DOC)
        print("STRUCTURE CHANGED %s -> %s, restored" % (before, after))
        return 1
    print("%d referenced, %d outstanding; citations/fields/sections intact %s"
          % (done, left, after))
    return 0


if __name__ == "__main__":
    sys.exit(main())
