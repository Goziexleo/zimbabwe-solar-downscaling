"""Cross-reference the Appendix C tables from the chapters that rest on them.

Appendix C was built from the evaluation CSVs that fed no table in the document.
Nine of its ten tables were then reachable only through the List of Tables, which
makes an appendix read as padding rather than as evidence: a supporting table that
nothing points at is not supporting anything.

Chapters 4 and 5 are regenerated by build_chapter4.py and build_chapter5.py on
every run of finalise_dissertation.sh, so the pointers to Tables C.5 to C.8 live
in those generators. Chapters 2 and 3 are edited in place, so theirs are here:

    C.2, C.3  the two pixel-wise grids, from Section 3.6.7
    C.4       the neural grid, from Section 3.6.7
    C.9       the perfect-prognosis transfer test, from Section 3.4.4
    C.10      the physiographic band means, from Section 2.4.3

Idempotent: each edit is keyed on text that the replacement does not reproduce,
and a second run reports the edits as already applied rather than doubling them.

    python add_appendix_c_crossrefs.py
"""

